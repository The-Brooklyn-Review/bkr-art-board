import { describe, expect, it } from "vitest";
import {
  createGallerySearch,
  hydrateGallery,
  type GalleryData,
  type GallerySubmission,
} from "./gallery";

const sub = (artistName: string): GallerySubmission => ({
  artistName,
  submissionTitle: "Title",
  coverLetter: "Statement",
  labels: [{ name: "painting", color: null }],
  publishedArtist: false,
  period: null,
  localReviewRecommendation: "none",
  submittableUrl: null,
  reviewUrl: "/submissions/s1",
  fileCount: 1,
});

const row = (id: string, submissionId: string) => ({
  id,
  submissionId,
  thumbnailUrl: `https://r2/${id}`,
  originalUrl: null,
  extractedText: null,
  autoGeneratedTags: null,
  assetType: "pdf_page",
  pageNumber: 1,
  fileIndex: 0,
  width: 10,
  height: 10,
  aspectRatio: 1,
  usedState: "available",
  originalFilename: null,
  pageCount: 2,
});

describe("hydrateGallery", () => {
  it("puts each submission's fields back on every one of its assets, in order", () => {
    const data: GalleryData = {
      assets: [row("a1", "s1"), row("a2", "s2"), row("a3", "s1")],
      submissions: { s1: sub("Ana"), s2: sub("Ben") },
    };
    const out = hydrateGallery(data);
    expect(out.map((a) => [a.id, a.artistName, a.coverLetter])).toEqual([
      ["a1", "Ana", "Statement"],
      ["a2", "Ben", "Statement"],
      ["a3", "Ana", "Statement"],
    ]);
    expect(out[0].thumbnailUrl).toBe("https://r2/a1");
  });
});

describe("createGallerySearch", () => {
  const tags = (concrete: string[], colors: string[] = []) => ({
    visionConcrete: concrete,
    visionInterpretive: [],
    dominantColors: colors,
    subjects: [],
    textThemes: [],
  });
  const asset = (
    id: string,
    over: Partial<ReturnType<typeof hydrateGallery>[number]>,
  ): ReturnType<typeof hydrateGallery>[number] => ({
    ...hydrateGallery({ assets: [row(id, "s")], submissions: { s: sub("Someone") } })[0],
    coverLetter: null,
    ...over,
  });
  const assets = [
    asset("layered", { autoGeneratedTags: tags(["layered paper", "textured surface"]) }),
    asset("red", { autoGeneratedTags: tags(["flower"], ["Reddish brown"]) }),
    asset("portrait", { autoGeneratedTags: tags(["portrait of a woman"]) }),
    asset("deep", {
      coverLetter: "My work explores ".padEnd(400, "x ") + " the herbarium of my grandmother",
    }),
  ];
  const search = createGallerySearch(assets);
  const ids = (q: string) => search(q)?.map((a) => a.id);

  it("matches a short word only at the start of a word", () => {
    expect(ids("red")).toEqual(["red"]); // not "layered", "textured"
  });
  it("still tolerates a typo in a longer word", () => {
    expect(ids("potrait")).toContain("portrait");
  });
  it("finds a word deep in a statement", () => {
    expect(ids("herbarium")).toEqual(["deep"]);
    expect(ids("grandmother HERBARIUM")).toEqual(["deep"]);
  });
  it("is no search at all for blank or single-letter queries", () => {
    expect(search("  ")).toBeNull();
    expect(search(" a ")).toBeNull();
  });
});

describe("badge labels", () => {
  it("picks out the poetry/fiction labels, in a fixed order", async () => {
    const { badgesOf, displayLabel } = await import("./labels");
    expect(
      badgesOf([{ name: "use for fiction" }, { name: "collage" }, { name: "use for poetry" }]),
    ).toEqual(["For poetry", "For fiction"]);
    expect(badgesOf([{ name: "collage" }])).toEqual([]);
    expect(displayLabel("use for poetry")).toBe("Use for Poetry");
    expect(displayLabel("painting/drawing")).toBe("Painting/Drawing");
  });
});
