// The gallery's page data as sent over the wire, and putting it back
// together in the browser. Pure — no Prisma here, so client components
// can import it.
import Fuse from "fuse.js";
import type { LibraryAsset } from "@/lib/art-library/getAssets";

/** Fields that are the same for every page of a submission. */
export type GallerySubmission = Pick<
  LibraryAsset,
  | "artistName"
  | "submissionTitle"
  | "coverLetter"
  | "labels"
  | "publishedArtist"
  | "period"
  | "localReviewRecommendation"
  | "submittableUrl"
  | "reviewUrl"
  | "fileCount"
>;

export type GalleryAssetRow = Omit<LibraryAsset, keyof GallerySubmission>;

/**
 * Each submission's fields are sent once instead of on every page — the
 * artist statement alone was ~330 KB repeated vs ~70 KB unique.
 */
export interface GalleryData {
  assets: GalleryAssetRow[];
  submissions: Record<string, GallerySubmission>;
}

/**
 * Every tag, deduplicated and sorted — the `combined` list the tagging
 * script stores (scripts/tag-all-artwork.ts), rebuilt here instead of sent.
 * Search weights it on top of the per-category lists, which ranks
 * tag matches higher.
 */
export function combinedTags(a: Pick<LibraryAsset, "autoGeneratedTags">): string[] {
  const t = a.autoGeneratedTags;
  if (!t) return [];
  return [
    ...new Set([
      ...t.visionConcrete,
      ...t.visionInterpretive,
      ...t.dominantColors,
      ...t.subjects,
      ...t.textThemes,
    ]),
  ].sort();
}

const SEARCH_KEYS = [
  { name: "artistName", weight: 0.4 },
  { name: "submissionTitle", weight: 0.3 },
  { name: "labels.name", weight: 0.2 },
  { name: "combinedTags", weight: 0.25, getFn: combinedTags },
  { name: "autoGeneratedTags.visionConcrete", weight: 0.15 },
  { name: "autoGeneratedTags.visionInterpretive", weight: 0.15 },
  { name: "autoGeneratedTags.subjects", weight: 0.1 },
  { name: "autoGeneratedTags.textThemes", weight: 0.1 },
  { name: "autoGeneratedTags.dominantColors", weight: 0.1 },
  { name: "extractedText", weight: 0.05 },
  { name: "coverLetter", weight: 0.05 },
];

/** Words of 4 letters or fewer must start a word: "red" finds red, reds,
 * reddish — not layered, textured, colored. */
const SHORT_WORD = 4;

function queryWords(query: string): string[] {
  return query
    .toLowerCase()
    .split(/\s+/)
    .filter((w) => w.length >= 2);
}

/** Matches `word` at the start of a word (any letter or digit before it
 * breaks the match). */
function wordStart(word: string): RegExp {
  const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?:^|[^\\p{L}\\p{N}])${escaped}`, "u");
}

/**
 * The gallery's search: returns a function from a query to matching
 * assets, best first.
 *
 * 1. Fuzzy (Fuse) over names, titles, labels and tags, so a typo in a
 *    longer word still finds it ("potrait"). It matches inside words, which
 *    for a short word is mostly noise — "red" hit every artwork through
 *    "layered", "textured" — so short words must also start a word
 *    somewhere in the artwork's text.
 * 2. Then exact word matches in the artist statement and page text that
 *    the fuzzy pass missed — Fuse only scores matches near the start of a
 *    field, so a word deep in a statement was never found.
 *
 * Returns null for no search (blank, or only single letters), so the
 * caller keeps its normal order.
 */
export function createGallerySearch(
  assets: LibraryAsset[],
): (query: string) => LibraryAsset[] | null {
  const fuse = new Fuse(assets, { keys: SEARCH_KEYS, threshold: 0.3, minMatchCharLength: 2 });
  const lower = (parts: (string | null | undefined)[]) =>
    parts.filter(Boolean).join("\n").toLowerCase();
  const allText = new Map(
    assets.map((a) => [
      a.id,
      lower([
        a.artistName,
        a.submissionTitle,
        ...a.labels.map((l) => l.name),
        ...combinedTags(a),
        a.coverLetter,
        a.extractedText,
      ]),
    ]),
  );
  const longText = new Map(assets.map((a) => [a.id, lower([a.coverLetter, a.extractedText])]));

  return (query) => {
    const words = queryWords(query);
    if (words.length === 0) return null;
    const starts = words.map(wordStart);
    const short = starts.filter((_, i) => words[i].length <= SHORT_WORD);
    const hits = fuse
      .search(query.trim())
      .map((r) => r.item)
      .filter((a) => short.every((re) => re.test(allText.get(a.id)!)));
    const seen = new Set(hits.map((a) => a.id));
    const more = assets.filter(
      (a) => !seen.has(a.id) && starts.every((re) => re.test(longText.get(a.id)!)),
    );
    return [...hits, ...more];
  };
}

export function hydrateGallery(data: GalleryData): LibraryAsset[] {
  return data.assets.map((a) => ({ ...data.submissions[a.submissionId], ...a }));
}

/** A stable pseudo-random rank for a submission under a shuffle seed
 * (FNV-1a) — the same seed always gives the same order. */
function shuffleRank(seed: number, id: string): number {
  let h = 0x811c9dc5 ^ seed;
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

/**
 * The gallery's browsing order: oldest reading period first (it's the one
 * to publish from first). With a shuffle seed, submissions are shuffled
 * within each period — an artist's pieces stay together, in their own
 * order — so the same artists aren't always at the top. Otherwise the
 * order the server sent. Doesn't mutate its input.
 */
export function browsingOrder<T extends Pick<LibraryAsset, "submissionId" | "period">>(
  assets: T[],
  shuffleSeed: number | null,
): T[] {
  return assets
    .map((a, i) => ({ a, i }))
    .sort(
      (x, y) =>
        (x.a.period?.sortKey ?? 0) - (y.a.period?.sortKey ?? 0) ||
        (shuffleSeed === null
          ? 0
          : shuffleRank(shuffleSeed, x.a.submissionId) -
            shuffleRank(shuffleSeed, y.a.submissionId)) ||
        x.i - y.i,
    )
    .map(({ a }) => a);
}
