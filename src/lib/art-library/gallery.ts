// The gallery's page data as sent over the wire, and putting it back
// together in the browser. Pure — no Prisma here, so client components
// can import it.
import type { LibraryAsset } from "@/lib/art-library/getAssets";

/** Fields that are the same for every page of a submission. */
export type GallerySubmission = Pick<
  LibraryAsset,
  | "artistName"
  | "submissionTitle"
  | "coverLetter"
  | "labels"
  | "publishedArtist"
  | "period"
  | "localReviewRecommendation"
  | "submittableUrl"
  | "reviewUrl"
  | "fileCount"
>;

export type GalleryAssetRow = Omit<LibraryAsset, keyof GallerySubmission>;

/**
 * Each submission's fields are sent once instead of on every page — the
 * artist statement alone was ~330 KB repeated vs ~70 KB unique.
 */
export interface GalleryData {
  assets: GalleryAssetRow[];
  submissions: Record<string, GallerySubmission>;
}

/**
 * Every tag, deduplicated and sorted — the `combined` list the tagging
 * script stores (scripts/tag-all-artwork.ts), rebuilt here instead of sent.
 * Search weights it on top of the per-category lists, which ranks
 * tag matches higher.
 */
export function combinedTags(a: Pick<LibraryAsset, "autoGeneratedTags">): string[] {
  const t = a.autoGeneratedTags;
  if (!t) return [];
  return [
    ...new Set([
      ...t.visionConcrete,
      ...t.visionInterpretive,
      ...t.dominantColors,
      ...t.subjects,
      ...t.textThemes,
    ]),
  ].sort();
}

/**
 * Whether every word of a search appears in the artist statement or the
 * page's own text. The fuzzy search only scores matches near the start of
 * a field (Fuse's location/distance), so a word deep in a statement was
 * never found; this exact pass covers the long fields.
 */
export function matchesLongText(
  a: Pick<LibraryAsset, "coverLetter" | "extractedText">,
  query: string,
): boolean {
  const words = query
    .toLowerCase()
    .split(/\s+/)
    .filter((w) => w.length >= 2);
  if (words.length === 0) return false;
  const text = `${a.coverLetter ?? ""}\n${a.extractedText ?? ""}`.toLowerCase();
  return words.every((w) => text.includes(w));
}

export function hydrateGallery(data: GalleryData): LibraryAsset[] {
  return data.assets.map((a) => ({ ...data.submissions[a.submissionId], ...a }));
}
