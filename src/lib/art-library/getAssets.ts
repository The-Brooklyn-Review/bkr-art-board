import type { Prisma } from "@prisma/client";
import {
  readingPeriodOf,
  submissionDateOf,
  type ReadingPeriod,
} from "@/lib/submittable/readingPeriod";
import { prisma } from "@/lib/db";
import { getSignedR2Url } from "@/lib/storage/r2";
import { signVariant } from "@/lib/storage/variants";
import { CONSIDERATION_LABEL_IDS } from "@/lib/submittable/consideration";
import type { GalleryData, GallerySubmission } from "@/lib/art-library/gallery";

export interface AutoGeneratedTags {
  visionConcrete: string[];
  visionInterpretive: string[];
  dominantColors: string[];
  subjects: string[];
  textThemes: string[];
  combined: string[];
}

/**
 * What the gallery sends for search: the tag lists without `combined`,
 * which is only their union (see scripts/tag-all-artwork.ts) and was
 * almost half the page's data.
 */
export type SearchTags = Omit<AutoGeneratedTags, "combined">;

/**
 * autoGeneratedTags is JSON stored in a plain string column (see
 * scripts/tag-all-artwork.ts), not a native Json column — nothing at the DB
 * level guarantees it's valid. An unguarded JSON.parse here would throw
 * inside Promise.all below and take down the entire art-library page for
 * everyone over a single malformed row (an interrupted tagging run, a
 * manual DB edit). Treat it the same as "not tagged yet" instead.
 */
function parseSearchTags(raw: string | null): SearchTags | null {
  if (!raw) return null;
  try {
    const { visionConcrete, visionInterpretive, dominantColors, subjects, textThemes } = JSON.parse(
      raw,
    ) as AutoGeneratedTags;
    return { visionConcrete, visionInterpretive, dominantColors, subjects, textThemes };
  } catch {
    console.warn(
      `[getGalleryData] malformed autoGeneratedTags JSON, ignoring: ${raw.slice(0, 100)}`,
    );
    return null;
  }
}

export interface LibraryAsset {
  id: string;
  submissionId: string;
  thumbnailUrl: string;
  /** The 600px-wide copy of the thumbnail, for the card's srcset (see
   * src/lib/storage/variants.ts); null for an unrecognised key. */
  cardUrl: string | null;
  /** App link that redirects to a fresh signed URL (api/assets/[id]/original). */
  originalUrl: string | null;
  artistName: string | null;
  submissionTitle: string | null;
  coverLetter: string | null;
  extractedText: string | null;
  labels: { name: string; color: string | null }[];
  autoGeneratedTags: SearchTags | null;
  assetType: string;
  pageNumber: number | null;
  fileIndex: number | null;
  width: number | null;
  height: number | null;
  aspectRatio: number | null;
  usedState: string;
  /** From a submission Submittable already marks accepted (see PUBLISHED_SUBMISSION_FILTER). */
  publishedArtist: boolean;
  /** The reading period it was submitted in ("Winter ’25"); null if the date is unknown. */
  period: ReadingPeriod | null;
  localReviewRecommendation: string;
  originalFilename: string | null;
  submittableUrl: string | null;
  reviewUrl: string;
  fileCount: number;
  pageCount: number;
}

/**
 * Which submissions belong in the gallery: Submittable status `completed`
 * with "Consider" or "Under Consideration" (one label to the app, see
 * src/lib/submittable/consideration.ts), and NOT labelled "acceptance" (BKR's marker for
 * work that's already been published). Undecided submissions are imported
 * too — for the Submission Reviewer — and must not leak in here. See
 * docs/SPEC-review-and-sync.md §2 and §9.3.
 *
 * Label names are matched case-insensitively because Submittable's own
 * casing is inconsistent. `officialStatus` is whatever the last import (or,
 * once it exists, the sync script) saw — it is not live.
 */
export const GALLERY_SUBMISSION_FILTER = {
  officialStatus: "completed",
  labels: { some: { label: { submittableLabelId: { in: [...CONSIDERATION_LABEL_IDS] } } } },
  NOT: {
    labels: { some: { label: { name: { equals: "acceptance", mode: "insensitive" } } } },
  },
} satisfies Prisma.SubmittableSubmissionWhereInput;

/**
 * Already accepted (slated or published) — hidden from the gallery by
 * default, shown with the "Include published artists" toggle, for the rare
 * case of publishing a second piece by the same artist.
 */
export const PUBLISHED_SUBMISSION_FILTER = {
  OR: [
    { officialStatus: { in: ["accepted", "published"] } },
    { labels: { some: { label: { name: { equals: "acceptance", mode: "insensitive" } } } } },
  ],
} satisfies Prisma.SubmittableSubmissionWhereInput;

/**
 * All visible-in-library assets from gallery submissions (see
 * GALLERY_SUBMISSION_FILTER above), with signed thumbnail URLs and everything
 * the grid needs. Fields that are the same for every page of a submission
 * (the artist statement above all) are sent once per submission and put
 * back on each asset in the browser — see hydrateGallery. Fetches everything in one shot rather than paginating —
 * fine at the current ~200-asset scale, filter/search happens client-side.
 * Revisit if the library grows substantially past this.
 *
 * Deliberately does NOT sign largeUrl here — that used to mean signing
 * 200+ R2 URLs nobody was about to look at. The client fetches a given
 * asset's large image on demand (api/assets/[id]/large) only when its lightbox
 * slide actually opens.
 *
 * Deliberately does NOT fetch hidden (visibleInArtLibrary: false) assets —
 * this view supports hiding a wrongly-visible page, but revealing a
 * wrongly-hidden one belongs in the Submission Review UI instead (see
 * src/components/submissions/SubmissionReviewClient.tsx), which shows a
 * full packet including hidden pages; pulling hidden assets in here too
 * would be scope creep for what's meant to be the fast browsing surface.
 */
export async function getGalleryData(
  options: { includePublished?: boolean } = {},
): Promise<GalleryData> {
  const assets = await prisma.artAsset.findMany({
    where: {
      visibleInArtLibrary: true,
      usedState: { not: "do_not_use" },
      submission: options.includePublished
        ? { OR: [GALLERY_SUBMISSION_FILTER, PUBLISHED_SUBMISSION_FILTER] }
        : GALLERY_SUBMISSION_FILTER,
    },
    // select, not include: the rows carry big raw-JSON columns (Submittable
    // responses, processing debug) the gallery never shows.
    select: {
      id: true,
      submissionId: true,
      submissionFileId: true,
      storagePathThumbnail: true,
      extractedText: true,
      autoGeneratedTags: true,
      assetType: true,
      pageNumber: true,
      fileIndex: true,
      width: true,
      height: true,
      aspectRatio: true,
      usedState: true,
      submissionFile: { select: { originalFilename: true } },
      submission: {
        select: {
          submittableId: true,
          artistName: true,
          submissionTitle: true,
          coverLetter: true,
          officialStatus: true,
          localReviewRecommendation: true,
          rawSubmissionJson: true, // for the reading period
          labels: { select: { label: { select: { name: true, color: true } } } },
          _count: { select: { files: true } },
        },
      },
    },
    orderBy: [{ submissionId: "asc" }, { fileIndex: "asc" }, { pageNumber: "asc" }],
  });

  const webBase = process.env.SUBMITTABLE_WEB_BASE_URL;

  // Precomputed once so each asset's pageCount lookup below is O(1) instead
  // of re-scanning the full asset list per asset (O(n²) at library scale).
  const pageCountByFileId = new Map<string, number>();
  for (const a of assets) {
    if (a.submissionFileId === null) continue;
    pageCountByFileId.set(a.submissionFileId, (pageCountByFileId.get(a.submissionFileId) ?? 0) + 1);
  }

  const submissions: Record<string, GallerySubmission> = {};
  for (const { submission: sub, submissionId } of assets) {
    if (submissions[submissionId]) continue;
    submissions[submissionId] = {
      artistName: sub.artistName,
      submissionTitle: sub.submissionTitle,
      coverLetter: sub.coverLetter,
      labels: sub.labels.map((l) => ({
        name: l.label.name.toLowerCase(),
        color: l.label.color,
      })),
      publishedArtist:
        ["accepted", "published"].includes(sub.officialStatus ?? "") ||
        sub.labels.some((l) => l.label.name.toLowerCase() === "acceptance"),
      period: readingPeriodOf(submissionDateOf(sub.rawSubmissionJson)),
      localReviewRecommendation: sub.localReviewRecommendation,
      // NOTE: must use submission.submittableId (Submittable's real ID),
      // not asset.submissionId (our internal FK/UUID) — these are two
      // different UUIDs and mixing them up produces a URL that 404s on
      // Submittable's site. Confirmed the two actually differ in real
      // data before fixing this (they're generated independently).
      submittableUrl: webBase ? `${webBase}/submissions/${sub.submittableId}` : null,
      reviewUrl: `/submissions/${submissionId}`,
      fileCount: sub._count.files,
    };
  }

  const rows = await Promise.all(
    assets.map(async (asset) => ({
      id: asset.id,
      submissionId: asset.submissionId,
      thumbnailUrl: await getSignedR2Url(asset.storagePathThumbnail),
      cardUrl: await signVariant(asset.storagePathThumbnail, "card"),
      // Not signed here: one signed URL per page of every PDF was ~120 KB
      // of the page, for a link that's rarely clicked.
      originalUrl: asset.submissionFile ? `/api/assets/${asset.id}/original` : null,
      extractedText: asset.extractedText,
      autoGeneratedTags: parseSearchTags(asset.autoGeneratedTags),
      assetType: asset.assetType,
      pageNumber: asset.pageNumber,
      fileIndex: asset.fileIndex,
      width: asset.width,
      height: asset.height,
      aspectRatio: asset.aspectRatio,
      usedState: asset.usedState,
      originalFilename: asset.submissionFile?.originalFilename ?? null,
      pageCount:
        asset.submissionFileId !== null ? (pageCountByFileId.get(asset.submissionFileId) ?? 0) : 0,
    })),
  );
  return { assets: rows, submissions };
}
